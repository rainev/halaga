import argparse
import json
import os
import sys
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app.us_valuation import build_us_valuation  # noqa: E402
from app.us_valuation.sec_client import SecClient  # noqa: E402
from app.us_valuation.xbrl import load_concept_config  # noqa: E402


CIK = "0000320193"
OUTPUT_ROOT = ROOT / "output" / "us-testing" / "aapl"
FRONTEND_MODULE = (
    ROOT / "frontend" / "src" / "research" / "generated" / "apple-valuation.js"
)
FRONTEND_AUDIT = ROOT / "frontend" / "public" / "data" / "apple-valuation-pipeline.json"
